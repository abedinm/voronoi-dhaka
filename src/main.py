"""Full pipeline — reproduces every deliverable from scratch.

Run with::

    python -m src.main

Phases: textbook (A) -> data (B) -> Voronoi + coverage -> zones (C) ->
recommendations -> visuals -> auto-stitched FINAL_REPORT.md.
"""

from __future__ import annotations

import pandas as pd

from . import (
    coverage,
    data_clean,
    data_fetch,
    recommend,
    textbook,
    viz,
    voronoi_dhaka,
    zones,
)
from . import config


def _rule(title: str) -> None:
    print("\n" + "=" * 68 + f"\n{title}\n" + "=" * 68)


def write_final_report(
    table: pd.DataFrame,
    coverages: dict,
    recs: dict,
    flagship_key: str,
) -> str:
    L: list[str] = []
    L.append("# Voronoi Analysis of Utility Services in Dhaka City\n")
    L.append(
        "_Auto-generated by `python -m src.main`. All distances and areas are "
        "computed in the metric CRS (UTM zone 46N, EPSG:32646)._\n"
    )

    L.append("## 1. Objective\n")
    L.append(
        "Evaluate how accessible Dhaka's utility services are — metro stations, "
        "hospitals, water sources, fuel stations, bus stops and fire stations — "
        "by partitioning the city into Voronoi cells around each facility, "
        "measuring coverage gaps, and recommending where new facilities would "
        "most improve access.\n"
    )

    L.append("## 2. Track A — textbook Voronoi (correctness proof)\n")
    L.append(
        "Three hand-sketches (P.B, M.R, Phiruz) redrawn as mathematically correct "
        "Voronoi diagrams: seeds in general position, straight perpendicular-"
        "bisector edges, exactly three cells meeting at every vertex, cells tiling "
        "the box. The blue overlay proves one edge is the perpendicular bisector "
        "of its two seeds.\n"
    )
    L.append("![Textbook Voronoi](../figures/textbook_all.png)\n")

    L.append("## 3. Method\n")
    L.append(
        "- **Data**: OpenStreetMap POIs via `osmnx` inside the Dhaka bounding box "
        f"`{config.DHAKA_BBOX}`; sparse categories fall back to labelled synthetic "
        "landmarks (see `data/SOURCE.md`).\n"
        "- **CRS**: I/O in EPSG:4326; all geometry/maths in EPSG:32646 (metres).\n"
        "- **Cleaning**: reproject, drop duplicates within "
        f"{config.MIN_SEED_DISTANCE:.0f} m, clip to the OSM admin boundary.\n"
        "- **Voronoi**: exact half-plane clipping against Delaunay neighbours "
        "(every interior edge is a true perpendicular bisector), then intersected "
        "with the city boundary.\n"
        "- **Metrics**: cell area (km²); nearest-facility distance on a "
        f"{config.GRID_SPACING_M:.0f} m grid (KDTree); a location is *underserved* "
        "if its nearest facility exceeds the per-service threshold; a cell is "
        "*underserved* if its area exceeds mean + 1σ. Access is area-weighted "
        "(no population raster).\n"
    )

    L.append("## 4. Per-service coverage\n")
    L.append(table.to_markdown(index=False))
    L.append("")
    for key in config.SERVICE_TYPES:
        label = config.SERVICE_TYPES[key].label
        L.append(f"### {label} (`{key}`)\n")
        L.append(f"![Voronoi {key}](../figures/voronoi_{key}.png)\n")
        L.append(f"![Heatmap {key}](../figures/heatmap_{key}.png)\n")

    L.append("## 5. Underserved-area summary\n")
    worst = table.sort_values("pct_grid_underserved", ascending=False)
    for _, r in worst.iterrows():
        L.append(
            f"- **{r['label']}**: {r['pct_grid_underserved']}% of the city is beyond "
            f"the {r['threshold_m']/1000:.1f} km threshold; worst-served point is "
            f"{r['max_nn_m']/1000:.1f} km from any facility "
            f"({r['n_underserved_cells']} oversized cells)."
        )
    L.append("")

    L.append("## 6. Recommendations (greedy, before → after)\n")
    for key, rec in recs.items():
        label = config.SERVICE_TYPES[key].label
        L.append(
            f"- **{label}**: adding {rec.k} sites cuts max access distance "
            f"{rec.before.max_nn_m/1000:.2f} km → {rec.after.max_nn_m/1000:.2f} km "
            f"and underserved grid points {rec.before.n_underserved} → "
            f"{rec.after.n_underserved}."
        )
    L.append("\nSee `recommendations.md` for exact coordinates. Example map:\n")
    L.append(f"![Recommendations {flagship_key}](../figures/recommendations_{flagship_key}.png)\n")

    L.append("## 7. Track C — zone-coloured flagship map\n")
    L.append(
        "The real service Voronoi, every cell coloured by the named Dhaka zone its "
        "seed falls in (nearest zone centre). Dashed lines are the coarse 8-zone "
        "Voronoi boundaries.\n"
    )
    L.append("![Zone flagship](../figures/zones_dhaka_flagship.png)\n")

    L.append("## 8. Limitations\n")
    L.append(
        "- OSM completeness varies by category; counts are a lower bound.\n"
        "- Sparse categories may include synthetic landmark points (flagged in "
        "`data/SOURCE.md` and the `source` column).\n"
        "- Access is area-weighted, not population-weighted — underserved fringe "
        "areas (rivers, low-density edges) are counted equally with dense wards.\n"
        "- The study window is the Dhaka bbox ∩ OSM admin polygon; peripheral "
        "cells extend to that boundary.\n"
    )

    L.append("## 9. Reproducibility\n")
    L.append(
        "```bash\n"
        "python -m venv .venv && source .venv/bin/activate\n"
        "pip install -r requirements.txt\n"
        "python -m src.main      # regenerates data, figures and this report\n"
        "pytest                  # correctness gates\n"
        "```\n"
    )

    text = "\n".join(L)
    out = config.REPORT_DIR / "FINAL_REPORT.md"
    out.write_text(text)
    return str(out)


def run(use_cache: bool = True) -> None:
    _rule("PHASE 3 — Track A: textbook Voronoi")
    for p in textbook.render_all():
        print("    saved", p)

    _rule("PHASE 4 — Track B: data")
    raw = data_fetch.fetch_all(use_cache=use_cache)
    data_clean.clean_all(raw)

    _rule("PHASE 5 — Voronoi + coverage")
    voronois = voronoi_dhaka.build_all()
    coverages, table = coverage.compute_all(voronois)

    flagship_key = max(voronois, key=lambda k: voronois[k].n)  # densest service

    _rule("PHASE 5B — Track C: zone-coloured maps")
    ref = zones.zone_reference()
    for key, sv in voronois.items():
        print("    zones ->", viz.plot_zone_colored_voronoi(sv, ref))
        viz.folium_zone_map(sv, ref)
    print("    flagship ->", viz.plot_zone_colored_voronoi(voronois[flagship_key], ref, flagship=True))

    _rule("PHASE 6 — recommendations")
    recs = recommend.recommend_all(voronois, coverages)
    recommend.write_recommendations_md(recs)

    _rule("PHASE 7 — visuals + interactive")
    for key, sv in voronois.items():
        cov = coverages[key]
        viz.plot_service_voronoi(sv, cov)
        viz.plot_nn_heatmap(sv, cov)
        viz.plot_recommendations(sv, recs[key])
        viz.folium_service_map(sv, cov, recs[key])
        print(f"    {key} visuals done")

    _rule("PHASE 8 — report")
    print("    report ->", write_final_report(table, coverages, recs, flagship_key))

    _rule("DONE — outputs")
    for sub in ("figures", "report"):
        d = config.OUTPUTS_DIR / sub
        for f in sorted(d.iterdir()):
            print("   ", f.relative_to(config.ROOT))


if __name__ == "__main__":
    run()
